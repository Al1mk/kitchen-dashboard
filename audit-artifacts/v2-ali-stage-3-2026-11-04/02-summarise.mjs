// Stage 3 summary (4 Nov 2026): reads the measured JSON of the "before" and "after" (Stage 3)
// captures and writes docs/evidence/v2-ali-stage-3-2026-11-04/measurements.md. Tooling only: it reports numbers, it
// does not decide whether they are good enough. Nominal emulation in headless Chromium; not the physical Elo screen,
// not a screen-reader session, not a usability result.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const EV = resolve(here, "../../docs/evidence/v2-ali-stage-3-2026-11-04");
const load = (label) => {
  const out = {};
  const root = `${EV}/${label}/data`;
  for (const ctx of readdirSync(root, { withFileTypes: true }).filter((d) => d.isDirectory())) {
    for (const f of readdirSync(`${root}/${ctx.name}`).filter((n) => n.endsWith(".json"))) out[`${ctx.name}/${f.replace(/\.json$/, "")}`] = JSON.parse(readFileSync(`${root}/${ctx.name}/${f}`, "utf8"));
  }
  return out;
};
const B = load("before");
const A = load("after");
const CTX = ["kiosk-touch-1080x1920", "kiosk-pointer-1080x1920", "sens-540x960", "laptop-1440x900", "phone-390x844"];
const PAGES = ["home", "newcomers", "map", "rooms", "schedule", "booking", "booking-cancel", "display"];
const KIOSK = new Set(["kiosk-touch-1080x1920", "kiosk-pointer-1080x1920", "sens-540x960"]);
const L = [];
const w = (s = "") => L.push(s);
const v = (x) => (x === null || x === undefined ? "–" : typeof x === "boolean" ? (x ? "yes" : "no") : String(x));

w("# Stage 3 measurements — baseline capture and Stage 3 working tree");
w();
w("Capture provenance: the supplied JSON does not contain a source-commit stamp. The original generator labelled the baseline a089f73, whereas the handoff said 3d45bb7. These captures show the recorded before/after behaviours; an exact baseline commit is not asserted. The separately source-matched validation and its commit are documented in README.md.");
w();
w("Generated by `audit-artifacts/v2-ali-stage-3-2026-11-04/02-summarise.mjs` from the JSON next to this file. **Nominal emulation in headless Chromium against two isolated copies with disposable databases, same script and synthetic data for both columns.** Browser-reported values (DOM, computed style, accessibility-tree snapshot). Not the physical Elo screen, not a screen-reader session, not a WCAG conformance audit, not a usability result.");
w();

w("## 1. Document language, title, headings, skip link, logo — 1080×1920 touch, every public page");
w();
w("| Page | Lang | Version | `<html lang>` | wrapper `lang` | h1 count | Headings (level: text) | Skip link | Logo link | `<main id>` |");
w("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |");
for (const page of PAGES) for (const lang of ["de", "en"]) for (const [lab, D] of [["before", B], ["after", A]]) {
  const r = D[`kiosk-touch-1080x1920/page-${page}-${lang}`]; if (!r) continue;
  const p = r.page;
  w(`| ${page} | ${lang} | ${lab} | ${p.htmlLang} | ${v(p.wrapperLang)} | ${p.h1Count} | ${p.headings.slice(0, 3).map(([l, t]) => `h${l}: ${t}`).join("; ")} | ${p.skipLink ? `"${p.skipLink.text}"` : "none"} | ${p.logoLink ? p.logoLink.href : "none"} | ${v(p.mainId)} |`);
}
w();

w("## 2. First Tab stop and what the skip link does (all contexts, all pages, DE and EN)");
w();
w("| Context | Version | Pages where the first Tab stop is the skip link | …whose activation puts focus on `<main id=main-content>` with the URL hash still empty | First Tab stop otherwise |");
w("| --- | --- | --- | --- | --- |");
for (const ctx of CTX) for (const [lab, D] of [["before", B], ["after", A]]) {
  const recs = PAGES.flatMap((p) => ["de", "en"].map((l) => D[`${ctx}/page-${p}-${l}`])).filter(Boolean);
  const skip = recs.filter((r) => r.firstTabStop && /Zum Inhalt springen|Skip to main content/.test(r.firstTabStop.name));
  const onMain = skip.filter((r) => r.afterSkipActivation?.tag === "MAIN" && r.afterSkipActivation?.id === "main-content" && r.afterSkipActivation.urlHash === "");
  const others = [...new Set(recs.filter((r) => !skip.includes(r)).map((r) => (r.firstTabStop ? r.firstTabStop.name : "nothing focusable")))].slice(0, 2).join(" / ");
  w(`| ${ctx} | ${lab} | ${skip.length} / ${recs.length} | ${onMain.length} | ${others || "–"} |`);
}
w("The 2 pages without a skip link in the \"after\" rows are `/display` in DE and EN: the announcement board has no dock before its content (the dock is its last element), so its first stops are the logo link and the scrolling list. That the next Tab stop after a skip lies **inside `<main>` and not in the dock** is asserted per page in `tests/e2e/stage3-accessibility.spec.ts` (7 routes × DE/EN × 5 contexts); it is not re-derived from this table.");
w();

w("## 3. /rooms: link names (browser accessibility tree), placeholder contrast, keyboard focus under the pinned chip bar");
w();
w("| Context | Lang | Version | Links in directory | Distinct names | Links sharing a name with another | Placeholder contrast | Shift+Tab onto a link just under the top edge: its top / bar bottom | Under the chip bar? |");
w("| --- | --- | --- | --- | --- | --- | --- | --- | --- |");
for (const ctx of CTX) for (const lang of ["de", "en"]) for (const [lab, D] of [["before", B], ["after", A]]) {
  const r = D[`${ctx}/rooms-a11y-${lang}`]; if (!r) continue;
  const s = r.shiftTabScenario;
  w(`| ${ctx} | ${lang} | ${lab} | ${r.roomLinkCount} | ${r.distinctLinkNames} | ${r.duplicateLinkNames} | ${r.placeholder ? `${r.placeholder.ratio}:1` : "–"} | ${s ? `${s.top} / ${v(s.barBottom)}` : "n/a (no pinned bar)"} | ${s ? (s.underBar ? "**yes**" : "no") : "n/a"} |`);
}
w();
const sample = (D) => D["kiosk-touch-1080x1920/rooms-a11y-de"]?.firstCardLinks ?? [];
w("Where the focused link ends up differs by language and is not a fixed number: Chrome aligns a link that was only partly behind the bar to the padded edge (107 px at 1080 px width), and centres one that was entirely behind it (809 px in the German run). Both are clear of the bar; the E2E test asserts clearance, not a position.");
w();
w("First room card, links as the accessibility tree reports them (DE, 1080×1920):");
w();
w(`- before: ${sample(B).map((l) => `\`${l}\``).join(", ")}`);
w(`- after: ${sample(A).map((l) => `\`${l}\``).join(", ")}`);
w();
w("Class-result links for the query \"HCI\" (DE, 1080×1920):");
w();
w(`- before: ${(B["kiosk-touch-1080x1920/rooms-class-links-de"]?.links ?? []).map((l) => `\`${l}\``).join(", ") || "none found"}`);
w(`- after: ${(A["kiosk-touch-1080x1920/rooms-class-links-de"]?.links ?? []).map((l) => `\`${l}\``).join(", ") || "none found"}`);
w();

w("## 4. Link names that occur several times with different targets, by page (after / before; top entries) — input for the open items of the other modules");
w();
w("| Page | Lang | Version | Links on page | Ambiguous names (name × occurrences, targets) |");
w("| --- | --- | --- | --- | --- |");
for (const page of PAGES) for (const lang of ["de", "en"]) for (const [lab, D] of [["before", B], ["after", A]]) {
  const r = D[`kiosk-touch-1080x1920/page-${page}-${lang}`]; if (!r) continue;
  const amb = r.page.ambiguousLinkNames.map((a) => `"${a.name}" ×${a.occurrences} (${a.targets} targets)`).join("; ");
  w(`| ${page} | ${lang} | ${lab} | ${r.page.linkCount} | ${amb || "none"} |`);
}
w();

w("## 5. /display: heading sizes (px) — the cards must not change");
w();
w("| Context | Lang | Version | Section heading px | Card title px | Screenshot SHA-256 (clock masked) |");
w("| --- | --- | --- | --- | --- | --- |");
for (const ctx of CTX) for (const lang of ["de", "en"]) for (const [lab, D] of [["before", B], ["after", A]]) {
  const r = D[`${ctx}/display-board-${lang}`]; if (!r) continue;
  w(`| ${ctx} | ${lang} | ${lab} | ${v(r.sizes.sectionHeading)} | ${v(r.sizes.cardTitle)} | ${r.pngSha256} |`);
}
w();
w("Identical hashes between before and after mean the rendered board is pixel-identical; different hashes mean pixels changed (here: only expected where the logo link or a focus state is drawn — see the screenshots).");
w();

w("## 5b. Page titles (after; unchanged by Stage 3, listed for the page-identity check)");
w();
w("| Page | DE title | EN title |");
w("| --- | --- | --- |");
for (const page of PAGES) w(`| ${page} | ${A[`kiosk-touch-1080x1920/page-${page}-de`]?.page.title} | ${A[`kiosk-touch-1080x1920/page-${page}-en`]?.page.title} |`);
w();

w("## 6. Kiosk contexts: focus placement summary");
w();
w("| Context | Version | Shift+Tab scenarios run | …focus under the chip bar | …focus under the dock |");
w("| --- | --- | --- | --- | --- |");
for (const ctx of CTX.filter((c) => KIOSK.has(c))) for (const [lab, D] of [["before", B], ["after", A]]) {
  const recs = ["de", "en"].map((l) => D[`${ctx}/rooms-a11y-${l}`]?.shiftTabScenario).filter(Boolean);
  w(`| ${ctx} | ${lab} | ${recs.length} | ${recs.filter((s) => s.underBar).length} | ${recs.filter((s) => s.underDock).length} |`);
}
w();
w("See `README.md` for the checks that were actually run and the limitations.");
writeFileSync(`${EV}/measurements.md`, L.join("\n") + "\n");
console.log("wrote", `${EV}/measurements.md`, L.length, "lines");
