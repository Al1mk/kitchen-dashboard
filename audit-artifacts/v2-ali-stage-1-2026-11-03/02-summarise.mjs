// Stage 1 summary (3 Nov 2026): reads the measured JSON of the "before" and "after" captures and writes
// docs/evidence/v2-ali-stage-1-2026-11-03/measurements.md. Tooling only. It reports numbers; it does not
// decide whether they are good enough. All numbers come from nominal emulation in headless Chromium.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const EV = resolve(here, "../../docs/evidence/v2-ali-stage-1-2026-11-03");
const load = (label) => {
  const out = {};
  const root = `${EV}/${label}/data`;
  for (const ctx of readdirSync(root, { withFileTypes: true }).filter((d) => d.isDirectory())) {
    for (const f of readdirSync(`${root}/${ctx.name}`).filter((n) => n.endsWith(".json"))) {
      out[`${ctx.name}/${f.replace(/\.json$/, "")}`] = JSON.parse(readFileSync(`${root}/${ctx.name}/${f}`, "utf8"));
    }
  }
  return out;
};
const before = load("before");
const after = load("after");
const idx = (label) => JSON.parse(readFileSync(`${EV}/${label}/data/_index.json`, "utf8"));
const pagesB = idx("before").pages;
const pagesA = idx("after").pages;

const f1 = (n) => (n === null || n === undefined ? "–" : typeof n === "string" ? n : Math.round(n * 10) / 10);
const lines = [];
const L = (s = "") => lines.push(s);

L("# Stage 1 measurements — before (V1 `a7903db`) and after (Stage 1 working tree)");
L();
L("Generated by `audit-artifacts/v2-ali-stage-1-2026-11-03/02-summarise.mjs` from the JSON next to this file. **Nominal emulation in headless Chromium against isolated copies with disposable databases.** These are CSS-pixel values of a simulated viewport, not measurements of the physical Elo screen, of reach or of touch hardware, and not a usability result.");
L();

// ---- 1. key pages, nominal kiosk -------------------------------------------------------------
L("## 1. Nominal kiosk 1080×1920, touch emulation on (German)");
L();
L("| Page | | Nav rows | Nav top (px) | Dock height (px / share) | Language switch top (px) | Tile min height | Root font | H1 | First paragraph | Content width |");
L("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |");
for (const page of ["home", "rooms", "booking", "map", "newcomers", "schedule", "booking-cancel", "display-many"]) {
  for (const [label, data] of [["before", before], ["after", after]]) {
    const r = data[`kiosk-touch-1080x1920/${page === "display-many" ? "display-many" : page}-de`];
    if (!r) continue;
    const geo = r.geo;
    const rows = (geo.rows ?? []).map((x) => (typeof x === "number" ? x : x.count)).join("+");
    const navTop = geo.navBox?.top ?? geo.navTop;
    const dock = geo.dock ? `${f1(geo.dock.h)} / ${Math.round(geo.dock.shareOfViewport * 100)} %` : "–";
    const langTop = geo.lang?.box?.top ?? null;
    const tile = geo.rows?.[0]?.minH ?? null;
    const lay = geo.layout ?? {};
    L(`| ${page} | ${label} | ${rows || "–"} | ${f1(navTop)} | ${dock} | ${f1(langTop)} | ${f1(tile)} | ${f1(lay.rootFontPx)} | ${f1(lay.h1Px)} | ${f1(lay.firstParagraphPx)} | ${f1(lay.contentWidth)} |`);
  }
}
L();
L("`–` = not applicable or not recorded in that capture (the V1 capture of the board states was a different record type).");
L();

// ---- 2. aggregate checks across every captured page ------------------------------------------
L("## 2. Every captured page record (8 public routes × DE/EN × contexts)");
L();
const ctxs = [...new Set(pagesA.map((p) => p.ctx))];
L("The focus column comes from a Tab walk limited to the first 70 tab stops of each page, so on long pages (Rooms, Map) it does not reach the end; the end-of-page and last-control checks are in the E2E spec `tests/e2e/kiosk-dock.spec.ts` (110 forward stops plus Shift+Tab to the last control).");
L();
L("| Context | Pages | Horizontal overflow | Last content/footer under the dock | Focused control under the dock | Dock height share |");
L("| --- | --- | --- | --- | --- | --- |");
for (const ctx of ctxs) {
  for (const [label, pages] of [["before", pagesB], ["after", pagesA]]) {
    const set = pages.filter((p) => p.ctx === ctx);
    const overflow = set.filter((p) => p.hOverflow).length;
    const covered = set.filter((p) => p.clearOfDock === false).length;
    const focus = set.filter((p) => p.focusCovered > 0).length;
    const shares = set.map((p) => p.dockShare).filter((x) => typeof x === "number");
    const share = shares.length ? `${Math.round(Math.min(...shares) * 100)}–${Math.round(Math.max(...shares) * 100)} %` : "–";
    L(`| ${ctx} ${label} | ${set.length} | ${overflow} | ${covered} | ${focus} | ${share} |`);
  }
}
L();

// ---- 3. booking confirm and receipt actions against the dock ---------------------------------
L("## 3. Booking: confirm and receipt actions relative to the dock (nominal kiosk contexts)");
L();
L("| Context | Language | Confirm button bottom | Dock top | Confirm inside viewport after the step opens | Receipt \"Fertig/Done\" bottom | Dock top |");
L("| --- | --- | --- | --- | --- | --- | --- |");
for (const ctx of ["kiosk-touch-1080x1920", "sens-1080x1700", "sens-540x960"]) {
  for (const lang of ["de", "en"]) {
    for (const [label, data] of [["before", before], ["after", after]]) {
      const r = data[`${ctx}/booking-review-${lang}`];
      const rc = data[`${ctx}/booking-receipt-${lang}`];
      if (!r) continue;
      const dockTop = r.geo.dock?.top ?? "–";
      const done = rc?.doneButton?.bottom ?? "–";
      const rcDock = rc?.geo?.pinned?.top ?? "–";
      L(`| ${ctx} ${label} | ${lang} | ${f1(r.confirmButton?.bottom)} | ${f1(dockTop)} | ${r.confirmButton?.inViewport ?? "–"} | ${done} | ${f1(rcDock)} |`);
    }
  }
}
L();
L("The confirm step does not scroll or focus itself into view in either version: that is Parsa's task AP-03, outside Stage 1. \"After\" guarantees only that the dock does not cover the button once it is scrolled or focused (see the spec). **Side effect to hand over:** the larger kiosk text makes the booking page longer, so at 1080×1920 the confirm button now lies further below the fold (bottom edge 2938 px against 2271 px before). AP-03 matters more, not less.");
L();

// ---- 4. announcement board ------------------------------------------------------------------
L("## 4. Announcement board (synthetic answers; nothing was written to the database)");
L();
L("| Context | State | Language | Nav rows | Language gap (px) | List ends above navigation | Cards / scrollable / clipped / last reachable |");
L("| --- | --- | --- | --- | --- | --- | --- |");
for (const ctx of ["kiosk-touch-1080x1920", "sens-540x960"]) {
  for (const state of ["many", "empty", "error", "loading"]) {
    for (const lang of ["de", "en"]) {
      for (const [label, data] of [["before", before], ["after", after]]) {
        const r = data[`${ctx}/display-${state}-${lang}`];
        if (!r) continue;
        const list = r.list ? `${r.list.cards} / ${r.list.scrollable} / ${r.list.clipped} / ${r.list.lastReachable}` : "–";
        L(`| ${ctx} ${label} | ${state} | ${lang} | ${(r.geo.rows ?? []).join("+")} | ${f1(r.geo.lang?.gap)} | ${r.listAboveNav ?? "–"} | ${list} |`);
      }
    }
  }
}
L();

writeFileSync(`${EV}/measurements.md`, lines.join("\n") + "\n");
console.log("wrote", `${EV}/measurements.md`, lines.length, "lines");
