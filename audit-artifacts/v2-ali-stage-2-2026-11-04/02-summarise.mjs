// Stage 2 summary (4 Nov 2026): reads the measured JSON of the "before" and "after" captures and writes
// docs/evidence/v2-ali-stage-2-2026-11-04/measurements.md. Tooling only: it reports numbers, it does not decide
// whether they are good enough. Nominal emulation in headless Chromium; not the physical Elo screen.
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const EV = resolve(here, "../../docs/evidence/v2-ali-stage-2-2026-11-04");
const load = (label) => {
  const out = {};
  const root = `${EV}/${label}/data`;
  for (const ctx of readdirSync(root, { withFileTypes: true }).filter((d) => d.isDirectory())) {
    for (const f of readdirSync(`${root}/${ctx.name}`).filter((n) => n.endsWith(".json"))) out[`${ctx.name}/${f.replace(/\.json$/, "")}`] = JSON.parse(readFileSync(`${root}/${ctx.name}/${f}`, "utf8"));
  }
  return out;
};
const B = load("before");
const A = load("after");
const idx = (label) => JSON.parse(readFileSync(`${EV}/${label}/data/_index.json`, "utf8"));
const pagesB = idx("before").pages;
const pagesA = idx("after").pages;
const n = (v) => (v === null || v === undefined ? "–" : typeof v === "number" ? Math.round(v * 10) / 10 : String(v));
const L = [];
const w = (s = "") => L.push(s);

w("# Stage 2 measurements — before (Stage 1 working tree) and after (Stage 2 working tree)");
w();
w("Generated by `audit-artifacts/v2-ali-stage-2-2026-11-04/02-summarise.mjs` from the JSON next to this file. **Nominal emulation in headless Chromium against isolated copies with disposable databases, same script and data for both columns.** CSS-pixel values of a simulated viewport; not the physical Elo screen, not reach, not touch, not a usability result.");
w();

w("## 1. Home — nominal kiosk 1080×1920, touch emulation on");
w();
w("| Language | Version | Cards | Columns | Smallest card (w × h px) | Tallest card h | Pictograms | Document height (screens) |");
w("| --- | --- | --- | --- | --- | --- | --- | --- |");
for (const lang of ["de", "en"]) for (const [lab, D] of [["before", B], ["after", A]]) {
  const r = D[`kiosk-touch-1080x1920/home-${lang}`]?.stage2; if (!r?.home) continue;
  w(`| ${lang} | ${lab} | ${r.home.cards} | ${r.home.columns} | ${n(r.home.minW)} × ${n(r.home.minH)} | ${n(r.home.maxH)} | ${r.home.pictograms} | ${n(r.screens)} |`);
}
w();

w("## 2. Newcomers — nominal kiosk 1080×1920");
w();
w("| Language | Version | Cards | Columns | Smallest card h | Help card full width | Pictograms | Prototype note | Note height / font (px) | Note fill | Document height (screens) |");
w("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |");
for (const lang of ["de", "en"]) for (const [lab, D] of [["before", B], ["after", A]]) {
  const r = D[`kiosk-touch-1080x1920/newcomers-${lang}`]?.stage2; if (!r?.newcomers) continue;
  const c = r.newcomers;
  w(`| ${lang} | ${lab} | ${c.cards} | ${c.columns} | ${n(c.minH)} | ${n(c.helpFullWidth)} | ${c.pictograms} | ${c.noteKind} | ${n(c.noteHeight)} / ${n(c.noteFontPx)} | ${c.noteBackground} | ${n(r.screens)} |`);
}
w();

w("## 3. Rooms — page length and card pitch (unfiltered directory, 54 demo rooms)");
w();
w("| Context | Language | Version | Document height (px) | Screens | Median card pitch (px) | First card h | Cards with actions in one row | Floor chips (bar h px, pinned) |");
w("| --- | --- | --- | --- | --- | --- | --- | --- | --- |");
for (const ctx of ["kiosk-touch-1080x1920", "sens-1080x1700", "sens-540x960", "laptop-1440x900", "phone-390x844"]) for (const lang of ["de", "en"]) for (const [lab, D] of [["before", B], ["after", A]]) {
  const r = D[`${ctx}/rooms-${lang}`]?.stage2; if (!r?.rooms) continue;
  const c = r.rooms;
  w(`| ${ctx} | ${lang} | ${lab} | ${n(r.docHeight)} | ${n(r.screens)} | ${n(c.medianPitch)} | ${n(c.firstCardH)} | ${c.actionsInOneRow} / ${c.cards} | ${c.chips.length ? `${c.chips.length} (${n(c.chipBar?.h)}, ${c.chipBar?.sticky})` : "none"} |`);
}
w();

w("## 4. Rooms search for a lecturer or course (\"HCI\": matching classes today, no room)");
w();
w("| Context | Language | Version | First group | Classes found | \"No room\" message | Message above the classes | Day-scope sentence |");
w("| --- | --- | --- | --- | --- | --- | --- | --- |");
for (const ctx of ["kiosk-touch-1080x1920", "sens-540x960", "laptop-1440x900"]) for (const lang of ["de", "en"]) for (const [lab, D] of [["before", B], ["after", A]]) {
  const r = D[`${ctx}/rooms-search-hci-${lang}`]?.stage2; if (!r?.search) continue;
  const s = r.search;
  w(`| ${ctx} | ${lang} | ${lab} | ${s.first} | ${s.classMatches} | ${s.noRoomMessage ? `"${s.noRoomMessage}…"` : "none"} | ${n(s.noRoomAboveClasses)} | ${s.scopeSentence} |`);
}
w();

w("## 5. Floor chips: where one tap lands (after only; V1/Stage 1 have no chips)");
w();
w("| Context | Language | Focused element | Heading top (px) | Chip bar bottom (px) | Bar pinned | URL hash added |");
w("| --- | --- | --- | --- | --- | --- | --- |");
for (const [k, r] of Object.entries(A)) {
  if (!k.includes("/rooms-floor-chip-")) continue;
  w(`| ${k.split("/")[0]} | ${r.lang} | ${r.landed.focusedId} | ${r.landed.headingTop} | ${r.landed.barBottom} | ${r.landed.barSticky} | ${r.landed.urlHasHash} |`);
}
w();

w("## 6. Every captured page record");
w();
w("| Context | Version | Page records | Horizontal overflow | Last content under the dock |");
w("| --- | --- | --- | --- | --- |");
for (const ctx of [...new Set(pagesA.map((p) => p.ctx))]) for (const [lab, P] of [["before", pagesB], ["after", pagesA]]) {
  const set = P.filter((p) => p.ctx === ctx);
  w(`| ${ctx} | ${lab} | ${set.length} | ${set.filter((p) => p.hOverflow).length} | ${set.filter((p) => p.clearOfDock === false).length} |`);
}
w();
if (existsSync(`${EV}/README.md`)) w("See `README.md` for the checks that were actually run and the limitations.");
writeFileSync(`${EV}/measurements.md`, L.join("\n") + "\n");
console.log("wrote", `${EV}/measurements.md`, L.length, "lines");
